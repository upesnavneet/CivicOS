"""Build supabase/migrations/0008_mumbai_data.sql from the extracted report tables and ward boundaries.
Usage: python3 build_sql.py praja_tables.json wards_simplified.json ../../supabase/migrations/0008_mumbai_data.sql"""
import json, sys

data = json.load(open(sys.argv[1])); wards = json.load(open(sys.argv[2])); out = sys.argv[3]
URL = {
    "p26": "https://praja.org/praja_docs/praja_downloads/Report%20on%20the%20Status%20of%20Civic%20Services,%20Environmental%20and%20Climate%20Issues%20in%20Mumbai%202026.pdf",
    "p25": "https://praja.org/praja_docs/praja_downloads/Report%20on%20the%20Status%20of%20Civic%20Issues%20in%20Mumbai.pdf",
}
q = lambda v: "null" if v is None else "'" + str(v).replace("'", "''") + "'"

# keep one value per key; the 2026 report wins over the 2025 report where both print the same year
seen, rows, skipped = {}, [], 0
# city-level issue figures: Table 2 is the report's own issue table, so it wins over totals of ward tables
order = sorted(data["records"], key=lambda r: (0 if r["source"] == "p26-t2" else 1 if r["source"].startswith("p26") else 2))
for r in order:
    if r["metric"] == "complaints_registered_cmp" or (r["zone"] and r["zone"] not in data["wards"]):
        skipped += 1; continue          # duplicate of complaints_registered / ward P/E has no boundary
    key = (r["zone"], r["year"], r["month"], r["metric"], r["category"])
    if key in seen:
        if seen[key] != r["value"]: print("NOTE two tables print different values, kept the first by priority:", key, seen[key], r["value"])
        continue
    seen[key] = r["value"]; rows.append(r)

used = sorted({r["source"] for r in rows})
L = []
L.append("""-- CivicOS 0008: published data for Mumbai. GENERATED by data/mumbai/build_sql.py - do not edit by hand.
--
-- Ward boundaries: DataMeet "Municipal Spatial Data", Mumbai BMC wards, CC BY-SA 2.5 India
--   https://github.com/datameet/Municipal_Spatial_Data/tree/master/Mumbai  (simplified to about 25 m)
-- Statistics: Praja Foundation reports (BMC data obtained under the RTI Act and from BMC's Environment
--   Status Report). Every row carries the report, table and PDF page it was read from.
-- No value in this file is estimated, interpolated or generated.

create or replace function app.load_mumbai_data(p_org uuid) returns jsonb
language plpgsql security definer set search_path = public, extensions as $fn$
declare
  v_city uuid;
begin
  if not exists (select 1 from organizations where id = p_org) then
    raise exception 'Unknown organization %', p_org;
  end if;

  -- re-running replaces the previous load
  delete from civic_indicators where organization_id = p_org;
  delete from data_sources     where organization_id = p_org;
  delete from health_index_snapshots where organization_id = p_org;
  delete from cities where organization_id = p_org and name = 'Mumbai';

  insert into cities (organization_id, name, state, is_synthetic_geometry)
  values (p_org, 'Mumbai', 'Maharashtra', false) returning id into v_city;

  insert into city_zones (organization_id, city_id, name, code, boundary, is_synthetic_geometry)
  select p_org, v_city, 'Ward ' || w.code, w.code,
         st_multi(st_setsrid(st_geomfromgeojson(w.geojson), 4326)), false
    from (values""")
L.append(",\n".join(f"      ({q(code)}, {q(json.dumps(wards[code]['geometry'], separators=(',', ':')))})" for code in data["wards"]))
L.append("""    ) as w(code, geojson);

  insert into data_sources (organization_id, id, publisher, report, table_ref, page, title, url, note) values""")
src_rows = [f"    (p_org, 'datameet-wards', 'DataMeet India community', 'Municipal Spatial Data: Mumbai BMC wards', null, null, "
            f"'Ward boundaries of the Brihanmumbai Municipal Corporation', 'https://github.com/datameet/Municipal_Spatial_Data/tree/master/Mumbai', "
            f"'CC BY-SA 2.5 India. Simplified for display.')"]
for sid in used:
    s = data["sources"][sid]
    src_rows.append(f"    (p_org, {q(sid)}, 'Praja Foundation', {q(s['report'].split(', ', 1)[1])}, {q(s['table'])}, {s['page']}, {q(s['title'])}, {q(URL[sid[:3]])}, null)")
L.append(",\n".join(src_rows) + ";")
L.append("""
  insert into civic_indicators (organization_id, zone_id, year, month, metric, category, value, unit, source_id)
  select p_org, z.id, v.year, v.month, v.metric, v.category, v.value, v.unit, v.source_id
    from (values""")
L.append(",\n".join(
    f"      ({q(r['zone'])}, {r['year']}, {r['month'] if r['month'] else 'null::int'}, {q(r['metric'])}, {q(r['category'])}, {r['value']}::numeric, {q(r['unit'])}, {q(r['source'])})"
    for r in rows))
L.append("""    ) as v(zone_code, year, month, metric, category, value, unit, source_id)
    left join city_zones z on z.organization_id = p_org and z.code = v.zone_code;

  -- 2025 ward populations as printed in the report (from BMC's Environment Status Report 2024-25)
  update city_zones z set population = ci.value::int
    from civic_indicators ci
   where ci.zone_id = z.id and ci.metric = 'population' and z.organization_id = p_org;

  perform app.compute_health_index(p_org, 2025);
  perform app.load_mumbai_models(p_org);      -- defined in 0009

  return jsonb_build_object(
    'wards',      (select count(*) from city_zones where organization_id = p_org),
    'indicators', (select count(*) from civic_indicators where organization_id = p_org),
    'sources',    (select count(*) from data_sources where organization_id = p_org),
    'models',     (select count(*) from ml_models where organization_id = p_org));
end $fn$;

revoke all on function app.load_mumbai_data(uuid) from public, anon, authenticated;
""")
open(out, "w").write("\n".join(L))
print(f"rows={len(rows)} skipped={skipped} sources={len(used)+1} bytes={sum(len(x) for x in L)}")
